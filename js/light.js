// שורה רומנטית לסוף המשחק
function romanceEpilogue(s) {
  const id = crush(s);
  if (!id || !s.crew[id]) return '';
  const c = COMPANIONS[id];
  const st = s.crew[id].status;
  if (st === 'dead') return `💔 ${c.name} לא ${c.f ? 'זכתה' : 'זכה'} לראות את הסוף הזה. אבל {אתה נושא|את נושאת} ${c.f ? 'אותה' : 'אותו'} איתך, לכל מקום.`;
  if (st === 'team') return `💞 ${c.name} ${c.f ? 'נשארה' : 'נשאר'} לצידך עד הסוף.${has(s, 'kissed') ? ' ועדיין דורכ' + (c.f ? 'ת' : '') + ' לך על הרגל כשאתם רוקדים.' : ''}`;
  if (st === 'sold') return `🥀 ${c.name} ${c.f ? 'נשארה' : 'נשאר'} מאחור, בבית ורקס. {אתה לא מפסיק|את לא מפסיקה} לחשוב ${c.f ? 'עליה' : 'עליו'}.`;
  return '';
}
