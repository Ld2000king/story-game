    name: `ההשתקפות — ${POWER_TREE[s.power][4].name}`,
    ability: ab,
    hp: s.maxHp + 24,
    atk: Math.max(5, pPowerBonus(s) - 1),
    def: Math.min(5, s.stats.agility + 1),
    dmg: 3 + Math.ceil(s.powerLevel / 2),
