function allyEvolved(s, id) {
  return !!(s.flags.allyEvo && s.flags.allyEvo[id]);
}

function allySkill(s, id) {
  return allyEvolved(s, id) ? ALLY_SKILLS_2[id] : ALLY_SKILLS[id];
}

// מתי כל חבר יכול להתעורר: הוא צריך להיות שם, והאמון שלו צריך להיות לפחות 4
function allyCanAwaken(s, id) {
  const c = s.crew[id];
  if (!c || allyEvolved(s, id)) return false;
  if (c.status === 'dead' || c.status === 'gone') return false;
  if (c.status !== 'team' && id !== 'maya') return false;
  return c.trust >= 4;
}

// שער: אם אחד מהחברים ברשימה יכול להתעורר עכשיו — עוברים לסצנת ההתעוררות, ומשם להמשך
function allyGate(s, ids, next) {
  const ready = ids.filter((id) => allyCanAwaken(s, id));
  if (!ready.length) return next;
  s.pendingAwaken = { queue: ready, next };
  return 'ally_awaken';
}

