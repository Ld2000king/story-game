function abyssNeed(s) {
  return 3 + (s.flags.darkness >= 4 ? 1 : 0);
}

function abyssDC(s) {
  return 12 + Math.floor((s.flags.darkness || 0) / 2);
}

function abyssBonus(s, id) {
  let b = Math.floor(trust(s, id) / 2);
  if (s.flags.romance === id) b += has(s, 'kissed') ? 4 : 3;
  const memory = { noa: 'noaGlow', itay: 'itayConfession', maya: 'knowsSeasons', daniel: 'standup', yoav: 'yoavRespect', alon: 'alonAlly', iris: 'danced', grom: 'gromSaved' }[id];
  if (memory && has(s, memory)) b += 2;
  return b;
}

